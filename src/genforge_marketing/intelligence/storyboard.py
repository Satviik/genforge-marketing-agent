"""Generate a standalone HTML storyboard from reconstructed evidence."""
from __future__ import annotations
import html
import json
from pathlib import Path
from typing import Any


def build_storyboard(timeline_report: dict[str, Any], frame_dir: str | Path | None = None) -> str:
    events = timeline_report.get("timeline", [])
    base = Path(frame_dir) if frame_dir else None
    cards = []
    for event in events:
        t = float(event.get("timestamp_seconds", 0))
        stamp = f"{int(t//60):02d}:{t%60:05.2f}"
        kind = str(event.get("event_type", "event"))
        evidence = html.escape(str(event.get("evidence", "")))
        interpretation = html.escape(str(event.get("interpretation", "")))
        image = ""
        if kind == "sampled_frame" and event.get("evidence"):
            path = Path(str(event["evidence"]))
            if base and not path.is_absolute():
                path = base / path
            src = html.escape(path.as_posix(), quote=True)
            image = f'<img loading="lazy" src="{src}" alt="Frame sampled at {stamp}">'
        cards.append(f'<article class="event"><div class="time">{stamp}</div><span class="tag">{html.escape(kind.replace("_", " "))}</span>{image}<div class="evidence">{evidence}</div><p>{interpretation}</p></article>')
    title = html.escape(str(timeline_report.get("source_file") or "Reel storyboard"))
    duration = timeline_report.get("duration_seconds")
    duration_text = f"{float(duration):.2f}s" if duration is not None else "unknown"
    summary = timeline_report.get("evidence_summary", {})
    summary_cards = "".join(f'<div class="stat"><strong>{html.escape(str(value))}</strong><span>{html.escape(str(key).replace("_"," "))}</span></div>' for key,value in summary.items())
    timeline = "".join(cards) or '<p>No events were present in this report.</p>'
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>GenForge Reel Storyboard — {title}</title>
<style>
:root{{color-scheme:dark;background:#101217;color:#e7e9ed;font:15px/1.5 system-ui,sans-serif}}
body{{margin:0;padding:clamp(16px,4vw,48px);max-width:1300px;margin:auto}}
h1{{font-size:clamp(1.5rem,4vw,2.5rem);margin:.2em 0}}.muted{{color:#a1a7b2}}
.stats{{display:flex;flex-wrap:wrap;gap:10px;margin:24px 0}}.stat{{background:#1c2028;border:1px solid #303643;border-radius:12px;padding:12px 18px;display:grid;gap:4px}}.stat strong{{font-size:1.4rem}}.stat span{{color:#a1a7b2;text-transform:capitalize}}
.timeline{{display:grid;gap:14px;border-left:2px solid #353b49;padding-left:20px}}
.event{{background:#1a1d24;border:1px solid #303643;border-radius:14px;padding:16px;position:relative;overflow-wrap:anywhere}}
.event:before{{content:"";position:absolute;left:-27px;top:22px;width:10px;height:10px;border-radius:50%;background:#8a9cff}}
.time{{font-weight:700;color:#9db1ff;font-variant-numeric:tabular-nums}}.tag{{display:inline-block;margin:6px 0;padding:3px 8px;background:#282f3d;border-radius:6px;font-size:.8rem;text-transform:capitalize;color:#c7d1f3}}
img{{display:block;max-width:min(100%,520px);max-height:400px;object-fit:contain;border-radius:10px;margin:10px 0;background:#08090b}}.evidence{{font-weight:600}}p{{color:#a1a7b2;margin:.5em 0 0}}
footer{{margin-top:28px;color:#858d99;font-size:.85rem}}
</style></head><body><h1>Reel Storyboard</h1><div class="muted">{title} · {duration_text}</div>
<section class="stats">{summary_cards}</section><section class="timeline">{timeline}</section>
<footer>Evidence-based storyboard generated by GenForge. Event labels are heuristics; this report does not claim semantic visual understanding or viewer-retention measurement.</footer></body></html>"""


def write_storyboard(timeline_report: dict[str, Any], output: str | Path, frame_dir: str | Path | None = None) -> Path:
    destination = Path(output)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(build_storyboard(timeline_report, frame_dir), encoding="utf-8")
    return destination
